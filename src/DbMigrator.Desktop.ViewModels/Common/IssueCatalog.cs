using DbMigrator.Core.Diagnostics;

namespace DbMigrator.Desktop.ViewModels;

/// <summary>What an issue code means to a DBA, and what to do about it.</summary>
public sealed record IssueHelp(string Title, string Meaning, string Action);

public static class IssueCatalog
{
    private static readonly Dictionary<string, IssueHelp> Help = new(StringComparer.Ordinal)
    {
        [IssueCodes.UnsupportedType] = new("Type copied as text",
            "The source type has no equivalent in the target, so values are copied as their text form.",
            "Check the affected columns; convert them in the target if the application needs the original type."),
        [IssueCodes.PrecisionReduced] = new("Fractional seconds reduced",
            "The target keeps fewer fractional-second digits than the source.",
            "Usually harmless. Check columns that compare timestamps for equality."),
        [IssueCodes.OffsetDropped] = new("UTC offset not kept",
            "Values keep their instant in time but lose the offset they were written with.",
            "If the application shows local times from the stored offset, store the offset in a separate column."),
        [IssueCodes.TypeChanged] = new("Type adjusted",
            "A column's type was changed so the target accepts it, without losing values.",
            "Nothing, unless the application depends on the exact type."),
        [IssueCodes.ComputedColumn] = new("Computed column copied as values",
            "The target column holds the computed values but no longer computes them.",
            "Recreate the expression in the target, as a generated column or a view, if new rows need it."),
        [IssueCodes.RowVersion] = new("rowversion copied as binary",
            "The values are copied, but the target will not set them on insert or update.",
            "Replace optimistic-concurrency checks that rely on rowversion, for example with a trigger."),
        [IssueCodes.DefaultNotTranslated] = new("Default not migrated",
            "A column default is source SQL that was not translated.",
            "Add the default in the target by hand."),
        [IssueCodes.IdentityDropped] = new("Identity not migrated",
            "The column's values are copied, but new rows get no automatic value.",
            "Add a sequence or identity in the target if new rows need generated values."),
        [IssueCodes.CheckConstraint] = new("Check constraint not migrated",
            "The constraint's expression is source SQL and was not translated.",
            "Recreate the constraint in the target by hand."),
        [IssueCodes.FilteredIndex] = new("Filtered index not migrated",
            "The index's predicate is source SQL and was not translated.",
            "Recreate it as a partial index in the target by hand."),
        [IssueCodes.UnsupportedIndex] = new("Index kind not migrated",
            "The target has no general equivalent of this index kind.",
            "Decide whether the target needs a different index for the same queries."),
        [IssueCodes.DisabledIndex] = new("Disabled index skipped",
            "The index is disabled in the source, so it was not created.",
            "Nothing, unless you meant to enable it."),
        [IssueCodes.NullsDistinct] = new("Unique index allows several NULLs",
            "The source allowed one NULL per unique key; this target version allows several.",
            "Upgrade the target to PostgreSQL 15 or later, or add a partial unique index."),
        [IssueCodes.ForeignKeyNotValidated] = new("Foreign key not validated",
            "The source never checked existing rows against this key, so the target does not either.",
            "Fix orphaned rows, then validate the constraint."),
        [IssueCodes.ForeignKeyTargetMissing] = new("Foreign key to a table left out",
            "The referenced table is not part of this migration, so the key was not created.",
            "Include the referenced table, or create the key by hand once it exists."),
        [IssueCodes.NameShortened] = new("Name shortened",
            "The name is longer than the target allows, so it was shortened with a hash suffix.",
            "Update queries that use the long name."),
        [IssueCodes.NameDeduplicated] = new("Name made unique",
            "The target needs index and constraint names to be unique per schema, so a suffix was added.",
            "Nothing, unless scripts refer to the index by name."),
        [IssueCodes.NameCollision] = new("Names collide",
            "Two source objects would get the same name in the target.",
            "Leave one of them out, or choose a different naming option."),
        [IssueCodes.TableExists] = new("Table already exists",
            "A table with the target name already exists, and nothing has been chosen for it yet.",
            "Choose to drop and recreate, truncate and reload, append to, or skip it."),
        [IssueCodes.DropCascade] = new("Table will be dropped",
            "The existing table is dropped and recreated, along with views and foreign keys that depend on it.",
            "Make sure nothing else in the target needs the table as it is."),
        [IssueCodes.CaseSensitivity] = new("Text comparisons change",
            "The source ignores case when comparing text; the target does not by default.",
            "Review queries and unique indexes on text that rely on case-insensitive matching."),
        [IssueCodes.DecimalRange] = new("Decimals wider than .NET",
            "The column can hold values with more significant digits than the copy can carry.",
            "Check whether such values exist; a row holding one stops that table's copy."),
        [IssueCodes.NulCharacterRemoved] = new("NUL characters removed",
            "The target cannot store the NUL character in text, so it was removed from some values.",
            "Check whether the application relied on NUL characters in this column."),
        [IssueCodes.SkippedColumn] = new("Column skipped",
            "The column was not copied.",
            "See the message for why."),
        [IssueCodes.NoTables] = new("Nothing to migrate",
            "No tables are selected.",
            "Select at least one table."),
        [IssueCodes.LimitedCatalogAccess] = new("Some tables may be invisible",
            "The login cannot see every table's definition, so some tables may be missing from the list.",
            "Grant VIEW DEFINITION on the database, or connect with a login that has it."),
        [IssueCodes.MissingPrivilege] = new("Missing privilege",
            "The login lacks a privilege the migration needs.",
            "Grant the privilege named in the message, or connect with another login."),
        [IssueCodes.SystemDatabase] = new("System database",
            "This is a system or maintenance database.",
            "Check you picked the database you meant to."),
    };

    public static IssueHelp For(string code) =>
        Help.TryGetValue(code, out var help) ? help : new IssueHelp(code, "See the message for details.", "See the message for details.");

    public static bool Knows(string code) => Help.ContainsKey(code);
}
