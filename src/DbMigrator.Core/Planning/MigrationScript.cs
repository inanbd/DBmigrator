using System.Text;
using DbMigrator.Core.Providers;

namespace DbMigrator.Core.Planning;

public enum ScriptPhase
{
    /// <summary>Drops, truncates and table creation; runs in one transaction where the engine allows it.</summary>
    BeforeData,
    /// <summary>Keys, indexes and identity resets; built after loading because that is much faster.</summary>
    AfterData,
}

public sealed record ScriptStep(ScriptPhase Phase, string Description, string Sql);

public sealed record MigrationScript(IReadOnlyList<ScriptStep> BeforeData, IReadOnlyList<ScriptStep> AfterData)
{
    /// <summary>The whole script as text, with a marker where the data copy happens.</summary>
    public string ToText(MigrationPlan plan)
    {
        var text = new StringBuilder();
        text.AppendLine("-- Generated by DbMigrator.");
        AppendSteps(text, "Before copying data", BeforeData);
        var copied = plan.Tables.Where(t => t.ReceivesData).ToList();
        text.AppendLine().AppendLine($"-- Data: DbMigrator bulk-loads {copied.Count} table(s) at this point.");
        foreach (var table in copied)
        {
            text.AppendLine($"--   {table.Source.Name} -> {table.Target}");
        }

        AppendSteps(text, "After copying data", AfterData);
        return text.ToString();
    }

    private static void AppendSteps(StringBuilder text, string heading, IReadOnlyList<ScriptStep> steps)
    {
        text.AppendLine().AppendLine($"-- {heading}");
        foreach (var step in steps)
        {
            text.AppendLine().AppendLine($"-- {step.Description}").Append(step.Sql).AppendLine(";");
        }
    }
}

public static class ScriptBuilder
{
    public static MigrationScript Build(MigrationPlan plan, ISqlDialect dialect)
    {
        var before = new List<ScriptStep>();
        foreach (var table in plan.Tables.Where(t => t.Action == TableAction.DropAndCreate).Reverse())
        {
            before.Add(new(ScriptPhase.BeforeData, $"Drop {table.Target}", dialect.DropTable(table.Target)));
        }

        foreach (var schema in plan.SchemasToCreate)
        {
            before.Add(new(ScriptPhase.BeforeData, $"Create schema {schema}", dialect.CreateSchema(schema)));
        }

        var truncated = plan.Tables.Where(t => t.Action == TableAction.Truncate).Select(t => t.Target).Reverse().ToList();
        if (truncated.Count > 0)
        {
            before.Add(new(ScriptPhase.BeforeData, $"Empty {string.Join(", ", truncated)}", dialect.TruncateTables(truncated)));
        }

        foreach (var table in plan.Tables.Where(t => t.CreatesTable))
        {
            before.Add(new(ScriptPhase.BeforeData, $"Create {table.Target} from {table.Source.Name}", dialect.CreateTable(table)));
        }

        var after = new List<ScriptStep>();
        foreach (var table in plan.Tables.Where(t => t.PrimaryKey is not null))
        {
            after.Add(new(ScriptPhase.AfterData, $"Primary key {table.PrimaryKey!.Name} on {table.Target}", dialect.AddPrimaryKey(table)));
        }

        foreach (var table in plan.Tables)
        {
            foreach (var index in table.Indexes)
            {
                after.Add(new(ScriptPhase.AfterData, $"Index {index.Name} on {table.Target}", dialect.CreateIndex(table, index)));
            }
        }

        foreach (var table in plan.Tables)
        {
            foreach (var fk in table.ForeignKeys)
            {
                after.Add(new(ScriptPhase.AfterData, $"Foreign key {fk.Name} on {table.Target}", dialect.AddForeignKey(table, fk)));
            }
        }

        foreach (var table in plan.Tables.Where(t => t.ReceivesData))
        {
            foreach (var column in table.Columns.Where(c => c.Identity is not null))
            {
                if (dialect.ResetIdentity(table, column) is { } sql)
                {
                    after.Add(new(ScriptPhase.AfterData, $"Continue identity {table.Target}.{column.Name} after the copied rows", sql));
                }
            }
        }

        return new MigrationScript(before, after);
    }
}
